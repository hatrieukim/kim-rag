import AppKit
import ApplicationServices
import Carbon.HIToolbox
import KimRagCore
import SwiftUI

/// Ghi app đang dùng, tiêu đề cửa sổ, lúc rời máy, clipboard và lệnh terminal, rồi gửi về server kim-rag.
/// Calendar events are read by `CalendarReader` and go through the same queue.
/// Mọi bộ lọc riêng tư chạy ở đây, trước khi sự kiện vào hàng đợi.
final class Recorder: NSObject, NSApplicationDelegate {
    static let pollSeconds: TimeInterval = 2
    static let tickSeconds: TimeInterval = 60
    static let maxTitle = 300
    static let maxCommand = 2000
    /// Posted by a second copy of the app started by hand; the running copy opens its window.
    static let openWindowNote = Notification.Name("com.kim.kimrag.mac.open-window")
    // Loại dữ liệu mà trình quản lý mật khẩu gắn vào clipboard để báo đây là nội dung không được lưu.
    static let secretPasteboardTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    var config = Config.load()
    let queue = EventQueue(url: Config.directory.appendingPathComponent("queue.jsonl"))
    let shellSpool = Config.directory.appendingPathComponent("shell.tsv")

    var trusted = false
    var paused = false
    var pausedAt: Date?
    var pauses: [(Date, Date)] = []
    var idleAway = false
    var screenAway = false          // máy khóa hoặc đang ngủ
    var lastKey = ""
    var focusPrivate = false        // cửa sổ đang dùng thuộc app bỏ qua hoặc có tiêu đề bị ẩn
    var focusApp: [String: Any] = [:]
    var lastPasteboard = NSPasteboard.general.changeCount
    var sending = false
    var lastSent: Date?
    var lastError: String?

    var statusItem: NSStatusItem!
    let model = PanelModel()
    let popover = NSPopover()
    var hotKey: EventHotKeyRef?
    var timers: [Timer] = []
    lazy var calendar = CalendarReader(
        queue: queue, config: { [unowned self] in self.config },
        onAccess: { [weak self] access in self?.model.calendarDenied = access == .denied },
        log: { [weak self] in self?.log($0) })
    lazy var meetings = MeetingRecorder(
        model: model, queue: queue, config: { [unowned self] in self.config },
        paused: { [unowned self] in self.paused }, log: { [weak self] in self?.log($0) })
    lazy var window = MainWindowController(model: {
        let m = WindowModel(api: Api(config: { [unowned self] in self.config }))
        m.onOpenConfig = { [weak self] in self?.openConfig() }
        return m
    }())
    lazy var sound = SoundWatcher(
        model: model, queue: queue, config: { [unowned self] in self.config }, paused: { [unowned self] in self.paused })
    lazy var room = RoomRecorder(
        model: model, config: { [unowned self] in self.config }, paused: { [unowned self] in self.paused },
        log: { [weak self] in self?.log($0) })
    lazy var wifi = WifiWatcher(
        queue: queue, paused: { [unowned self] in self.paused }, log: { [weak self] in self?.log($0) })

    // MARK: - Khởi động

    func applicationDidFinishLaunching(_ notification: Notification) {
        let prompt = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        trusted = AXIsProcessTrustedWithOptions([prompt: true] as CFDictionary)
        setupPanel()
        setupMenu()
        registerHotKey()
        observe()
        queue.add(type: "start")
        poll(force: true)
        timers = [
            Timer.scheduledTimer(withTimeInterval: Self.pollSeconds, repeats: true) { [weak self] _ in self?.poll() },
            Timer.scheduledTimer(withTimeInterval: 1, repeats: true) { [weak self] _ in self?.pollClipboard() },
            Timer.scheduledTimer(withTimeInterval: 5, repeats: true) { [weak self] _ in self?.readShell() },
            Timer.scheduledTimer(withTimeInterval: Self.tickSeconds, repeats: true) { [weak self] _ in self?.tick() },
            Timer.scheduledTimer(withTimeInterval: config.sendEverySeconds, repeats: true) { [weak self] _ in self?.send() },
        ]
        calendar.start()
        meetings.onChange = { [weak self] in self?.updateIcon() }
        meetings.panelVisible = { [weak self] in self?.popover.isShown ?? false }
        meetings.start()
        room.panelVisible = { [weak self] in self?.popover.isShown ?? false }
        room.start()
        sound.start()
        wifi.start()
        send()
        log("bắt đầu ghi, \(queue.count) sự kiện đang chờ gửi, Accessibility: \(trusted ? "có" : "chưa có")")
    }

    /// Clicking the Dock icon opens the window; closing the window leaves the app recording.
    func applicationShouldHandleReopen(_ sender: NSApplication, hasVisibleWindows flag: Bool) -> Bool {
        if !flag { openWindow() }
        return true
    }

    func applicationShouldTerminateAfterLastWindowClosed(_ sender: NSApplication) -> Bool { false }

    @objc func openWindow() {
        popover.performClose(nil)
        reloadConfig()
        window.present()
    }

    func applicationWillTerminate(_ notification: Notification) {
        meetings.stop(reason: "quit")
        meetings.flush()
        room.stop(reason: "quit")
        room.flush()
        sound.halt()
        queue.add(type: "stop")
    }

    private func observe() {
        let ws = NSWorkspace.shared.notificationCenter
        ws.addObserver(forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main) { [weak self] _ in
            self?.poll()
        }
        ws.addObserver(forName: NSWorkspace.willSleepNotification, object: nil, queue: .main) { [weak self] _ in
            self?.sound.halt()
            self?.room.sleep()
            self?.setScreenAway(true, reason: "sleep")
        }
        ws.addObserver(forName: NSWorkspace.didWakeNotification, object: nil, queue: .main) { [weak self] _ in
            self?.setScreenAway(false, reason: "sleep")
            self?.sound.wake()
            self?.room.wake()
            self?.wifi.wake()
        }
        ws.addObserver(forName: NSWorkspace.willPowerOffNotification, object: nil, queue: .main) { [weak self] _ in
            self?.sound.halt()
            self?.room.stop(reason: "quit")
            self?.setScreenAway(true, reason: "off")
        }
        let dist = DistributedNotificationCenter.default()
        dist.addObserver(forName: Self.openWindowNote, object: nil, queue: .main) { [weak self] _ in
            self?.openWindow()
        }
        dist.addObserver(forName: .init("com.apple.screenIsLocked"), object: nil, queue: .main) { [weak self] _ in
            self?.setScreenAway(true, reason: "lock")
        }
        dist.addObserver(forName: .init("com.apple.screenIsUnlocked"), object: nil, queue: .main) { [weak self] _ in
            self?.setScreenAway(false, reason: "lock")
        }
    }

    // MARK: - App đang dùng và lúc rời máy

    func poll(force: Bool = false) {
        guard !paused, !screenAway else { return }
        if !trusted { trusted = AXIsProcessTrusted() }
        var force = force
        let idle = CGEventSource.secondsSinceLastEventType(.combinedSessionState, eventType: CGEventType(rawValue: ~0)!)
        if !idleAway && idle >= config.idleSeconds {
            idleAway = true
            queue.add(type: "away", payload: ["reason": "idle"], at: Date().addingTimeInterval(-idle))
        } else if idleAway && idle < Self.pollSeconds * 2 {
            idleAway = false
            queue.add(type: "back", payload: ["reason": "idle"], at: Date().addingTimeInterval(-idle))
            force = true
        }
        focus(force: force)
        model.trusted = trusted
        model.waiting = queue.count
    }

    private func focus(force: Bool) {
        guard let app = NSWorkspace.shared.frontmostApplication else { return }
        let bundle = app.bundleIdentifier ?? ""
        var payload: [String: Any]
        if config.ignoreApps.contains(bundle) {
            payload = ["ignored": true]
        } else {
            payload = ["app": app.localizedName ?? bundle, "bundle": bundle]
            if trusted, let title = windowTitle(pid: app.processIdentifier), !title.isEmpty {
                if config.hidesTitle(title) {
                    payload["hidden"] = true
                } else {
                    payload["title"] = String(Scrub.clean(title).prefix(Self.maxTitle))
                }
            }
        }
        focusPrivate = payload["ignored"] != nil || payload["hidden"] != nil
        model.currentApp = payload["ignored"] != nil ? "" : (payload["app"] as? String ?? "")
        model.currentTitle = payload["title"] as? String ?? ""
        model.currentPrivate = focusPrivate
        focusApp = payload["ignored"] != nil ? [:] : ["app": payload["app"] ?? "", "bundle": bundle]
        let key = String(describing: payload.sorted { $0.key < $1.key }.map { "\($0.key)=\($0.value)" })
        if force || key != lastKey {
            lastKey = key
            queue.add(type: "focus", payload: payload)
        }
    }

    private func windowTitle(pid: pid_t) -> String? {
        let element = AXUIElementCreateApplication(pid)
        AXUIElementSetMessagingTimeout(element, 0.5)  // app treo thì bỏ qua lượt này, không treo theo
        var window: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXFocusedWindowAttribute as CFString, &window) == .success,
              let window, CFGetTypeID(window) == AXUIElementGetTypeID() else { return nil }
        var title: CFTypeRef?
        guard AXUIElementCopyAttributeValue(window as! AXUIElement, kAXTitleAttribute as CFString, &title) == .success
        else { return nil }
        return (title as? String)?.trimmingCharacters(in: .whitespacesAndNewlines)
    }

    private func setScreenAway(_ away: Bool, reason: String) {
        if away {
            if !screenAway && !paused { queue.add(type: "away", payload: ["reason": reason]) }
            screenAway = true
        } else if screenAway {
            screenAway = false
            guard !paused else { return }
            queue.add(type: "back", payload: ["reason": reason])
            idleAway = false
            poll(force: true)
        }
    }

    /// Nhịp đều mỗi phút cho server biết chương trình vẫn chạy. Mất nhịp lâu nghĩa là máy tắt hoặc chương trình chết.
    private func tick() {
        if popover.isShown { fetchToday() }
        guard !paused, !screenAway, !idleAway else { return }
        queue.add(type: "tick")
    }

    // MARK: - Clipboard và lệnh terminal

    private func pollClipboard() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastPasteboard else { return }
        lastPasteboard = pb.changeCount
        guard !paused, !focusPrivate else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.secretPasteboardTypes) else { return }
        guard let raw = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines), !raw.isEmpty
        else { return }
        let clean = Scrub.clean(raw)
        let text = clean.count > config.clipboardMaxChars ? String(clean.prefix(config.clipboardMaxChars)) + " …" : clean
        var payload = focusApp
        payload["text"] = text
        payload["chars"] = raw.count
        queue.add(type: "clipboard", payload: payload)
    }

    private func readShell() {
        for c in ShellSpool.take(from: shellSpool) where !wasPaused(at: c.startedAt) {
            queue.add(type: "shell", payload: [
                "cmd": Scrub.clean(String(c.command.prefix(Self.maxCommand))),
                "cwd": c.cwd,
                "status": c.status,
                "seconds": (c.seconds * 10).rounded() / 10,
            ], at: c.startedAt)
        }
    }

    private func wasPaused(at date: Date) -> Bool {
        if paused, let start = pausedAt, date >= start { return true }
        return pauses.contains { date >= $0.0 && date <= $0.1 }
    }

    // MARK: - Tạm dừng

    @objc func togglePause() {
        if paused {
            paused = false
            if let start = pausedAt { pauses = Array((pauses + [(start, Date())]).suffix(50)) }
            pausedAt = nil
            queue.add(type: "back", payload: ["reason": "pause"])
            idleAway = false
            lastPasteboard = NSPasteboard.general.changeCount
            poll(force: true)
            log("tiếp tục ghi")
        } else {
            queue.add(type: "away", payload: ["reason": "pause"])
            meetings.stop(reason: "pause")
            paused = true
            pausedAt = Date()
            log("tạm dừng ghi")
        }
        model.paused = paused
        room.poll()
        updateIcon()
    }

    /// The room switch on the panel: written to mac.json so it lasts across restarts.
    func setRoom(_ on: Bool) {
        do {
            try Config.set("room", on)
        } catch {
            log("could not save the room setting: \(error)")
            return
        }
        reloadConfig()
        room.poll()
        log("room recording turned \(on ? "on" : "off")")
    }

    private func registerHotKey() {
        var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
        InstallEventHandler(GetApplicationEventTarget(), { _, _, context in
            guard let context else { return noErr }
            Unmanaged<Recorder>.fromOpaque(context).takeUnretainedValue().togglePause()
            return noErr
        }, 1, &spec, Unmanaged.passUnretained(self).toOpaque(), nil)
        let id = EventHotKeyID(signature: OSType(0x4B52_4147), id: 1)  // "KRAG"
        RegisterEventHotKey(UInt32(kVK_ANSI_P), UInt32(controlKey | optionKey | cmdKey), id,
                            GetApplicationEventTarget(), 0, &hotKey)
    }

    // MARK: - Gửi về server

    private func send() {
        guard !sending, let (body, count) = queue.batch(), let url = URL(string: config.server + "/events") else { return }
        var request = URLRequest(url: url, timeoutInterval: 20)
        request.httpMethod = "POST"
        request.setValue("application/json", forHTTPHeaderField: "Content-Type")
        if !config.token.isEmpty { request.setValue("Bearer \(config.token)", forHTTPHeaderField: "Authorization") }
        request.httpBody = body
        sending = true
        URLSession.shared.dataTask(with: request) { [weak self] data, response, error in
            DispatchQueue.main.async {
                guard let self else { return }
                self.sending = false
                let code = (response as? HTTPURLResponse)?.statusCode ?? 0
                switch code {
                case 200:
                    self.queue.drop(count)
                    self.lastSent = Date()
                    self.lastError = nil
                    if self.queue.count > 0 { self.send() }
                    if self.popover.isShown { self.fetchToday() }
                case 400, 422:
                    // Server từ chối nội dung: gửi lại cũng vậy, bỏ mẻ này để hàng không kẹt mãi.
                    let detail = data.flatMap { String(data: $0, encoding: .utf8) } ?? ""
                    self.log("server từ chối \(count) sự kiện (HTTP \(code)), bỏ qua: \(detail.prefix(300))")
                    self.queue.drop(count)
                default:
                    self.lastError = error.map { _ in "server chưa chạy" } ?? "HTTP \(code)"
                }
                self.model.waiting = self.queue.count
                self.model.lastSent = self.lastSent
                self.model.lastError = self.lastError
            }
        }.resume()
    }

    // MARK: - Bảng nhỏ trên thanh menu

    private func setupPanel() {
        statusItem = NSStatusBar.system.statusItem(withLength: NSStatusItem.variableLength)
        statusItem.button?.target = self
        statusItem.button?.action = #selector(togglePanel)
        model.onTogglePause = { [weak self] in self?.togglePause() }
        model.onToggleRoom = { [weak self] in self?.setRoom($0) }
        model.onEndConversation = { [weak self] in self?.room.endConversation() }
        model.onOpenConfig = { [weak self] in self?.popover.performClose(nil); self?.openConfig() }
        model.onOpenWindow = { [weak self] in self?.openWindow() }
        model.onQuit = { NSApp.terminate(nil) }
        model.trusted = trusted
        popover.behavior = .transient
        popover.contentViewController = NSHostingController(rootView: PanelView(model: model))
        updateIcon()
    }

    @objc func togglePanel() {
        if popover.isShown {
            popover.performClose(nil)
            return
        }
        guard let button = statusItem.button else { return }
        reloadConfig()  // sửa file cấu hình xong, mở bảng là có hiệu lực
        model.waiting = queue.count
        fetchToday()
        popover.show(relativeTo: button.bounds, of: button, preferredEdge: .minY)
        popover.contentViewController?.view.window?.makeKey()
    }

    private func updateIcon() {
        var name = paused ? "pause.circle" : "record.circle"
        var label = paused ? "kim-rag: đã tạm dừng" : "kim-rag: đang ghi"
        if let m = model.meeting {
            name = m.problem ? "exclamationmark.triangle" : "person.2.wave.2"
            label = m.problem ? "kim-rag: meeting recording has a problem" : "kim-rag: recording a meeting"
        }
        let image = NSImage(systemSymbolName: name, accessibilityDescription: label)
        image?.isTemplate = true
        statusItem.button?.image = image
    }

    /// Lấy thời gian hôm nay từ server. Server tắt thì bảng ghi là chưa lấy được, không chặn gì khác.
    private func fetchToday() {
        guard let url = URL(string: config.server + "/mac/today") else { return }
        var request = URLRequest(url: url, timeoutInterval: 5)
        if !config.token.isEmpty { request.setValue("Bearer \(config.token)", forHTTPHeaderField: "Authorization") }
        URLSession.shared.dataTask(with: request) { [weak self] data, response, _ in
            let decoder = JSONDecoder()
            decoder.keyDecodingStrategy = .convertFromSnakeCase
            let ok = (response as? HTTPURLResponse)?.statusCode == 200
            let today = ok ? data.flatMap { try? decoder.decode(Today.self, from: $0) } : nil
            DispatchQueue.main.async { self?.model.today = today }
        }.resume()
    }

    /// The menu bar of a regular app: without an Edit menu, copy and paste do not work in text fields.
    private func setupMenu() {
        let main = NSMenu()
        func submenu(_ title: String, _ items: [NSMenuItem]) -> NSMenu {
            let menu = NSMenu(title: title)
            items.forEach(menu.addItem)
            let holder = NSMenuItem()
            holder.submenu = menu
            main.addItem(holder)
            return menu
        }
        func item(_ title: String, _ action: Selector?, _ key: String = "", _ mods: NSEvent.ModifierFlags = .command) -> NSMenuItem {
            let i = NSMenuItem(title: title, action: action, keyEquivalent: key)
            i.keyEquivalentModifierMask = mods
            return i
        }
        let open = item("Mở cửa sổ kim-rag", #selector(openWindow), "0")
        open.target = self
        let config = item("Cấu hình…", #selector(openConfig), ",")
        config.target = self
        let pause = item("Tạm dừng / ghi tiếp", #selector(togglePauseFromMenu), "p", [.command, .option, .control])
        pause.target = self
        _ = submenu("kim-rag", [
            item("Về kim-rag", #selector(NSApplication.orderFrontStandardAboutPanel(_:))), .separator(),
            open, config, pause, .separator(),
            item("Ẩn kim-rag", #selector(NSApplication.hide(_:)), "h"),
            item("Ẩn các app khác", #selector(NSApplication.hideOtherApplications(_:)), "h", [.command, .option]),
            .separator(),
            item("Thoát kim-rag (dừng ghi)", #selector(NSApplication.terminate(_:)), "q"),
        ])
        _ = submenu("Sửa", [
            item("Hoàn tác", Selector(("undo:")), "z"), item("Làm lại", Selector(("redo:")), "z", [.command, .shift]),
            .separator(),
            item("Cắt", #selector(NSText.cut(_:)), "x"), item("Chép", #selector(NSText.copy(_:)), "c"),
            item("Dán", #selector(NSText.paste(_:)), "v"), item("Chọn hết", #selector(NSText.selectAll(_:)), "a"),
        ])
        _ = submenu("Xem", [item("Ẩn/hiện thanh bên", #selector(NSSplitViewController.toggleSidebar(_:)), "s", [.command, .control])])
        let windowMenu = submenu("Cửa sổ", [
            item("Thu nhỏ", #selector(NSWindow.performMiniaturize(_:)), "m"),
            item("Đóng", #selector(NSWindow.performClose(_:)), "w"),
        ])
        NSApp.mainMenu = main
        NSApp.windowsMenu = windowMenu
    }

    @objc private func togglePauseFromMenu() { togglePause() }

    @objc func openConfig() {
        _ = Config.load()
        NSWorkspace.shared.open(Config.file)
    }

    @objc func reloadConfig() {
        config = Config.load()
        lastKey = ""
        poll(force: true)
        if calendar.access == .granted { calendar.sync() } else if config.calendar && calendar.access == .off { calendar.start() }
        log("đã nạp lại cấu hình")
    }

    private func log(_ message: String) {
        FileHandle.standardError.write(Data("\(EventQueue.timestamp(Date())) \(message)\n".utf8))
    }
}
